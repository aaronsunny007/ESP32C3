#!/usr/bin/env python3
"""Draws the power-on greeting for the 0.96" OLED and writes firmware/bag_clip/greeting_img.h.

Two 128x64 screens, panda on the left and text on the right:
  1. "Hpy bday" / "Kusuma."           (shown at power-on, the panda wears its cap)
  2. "From your" / "lovely" / "panda"  (after a tap the cap lifts off, then this screen)
The cap is a separate sprite (GREET_HAT + GREET_HAT_MASK at GREET_HAT_X/Y) so the
firmware can animate it off the panda's head.

Change the lines in SCREENS and run it again:
    python3 tools/make_oled_panda.py
It also writes OLED-look previews (6x size) next to the header: greeting_1_preview.png ...
Needs Pillow (pip install pillow).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from PIL import Image, ImageDraw, ImageFont
from png_to_bitmap import to_array

ROOT = Path(__file__).resolve().parent.parent
OUT_H = ROOT / "firmware" / "bag_clip" / "greeting_img.h"
PREVIEW_DIR = ROOT / "docs" / "images"

SCREENS = [
    ("GREET_BDAY", ["Hpy bday", "Kusuma."]),
    ("GREET_FROM", ["From your", "lovely", "panda"]),
]

BOLD = "/usr/share/fonts/truetype/dejavu/DejaVuSans-Bold.ttf"
TEXT_X, TEXT_W = 66, 61          # right half of the screen, 1 px margin


def panda():
    """64x64 1-bit panda with a bow tie, lit = white. Drawn 4x larger, then shrunk."""
    n = 256
    im = Image.new("L", (n, n), 0)
    d = ImageDraw.Draw(im)

    def e(cx, cy, rx, ry, fill, outline=None, w=0):
        d.ellipse([cx - rx, cy - ry, cx + rx, cy + ry], fill=fill, outline=outline, width=w)

    e(128, 246, 70, 56, 255)                                   # body
    e(52, 66, 32, 32, 0, 255, 9); e(204, 66, 32, 32, 0, 255, 9)  # ears: dark, lit outline
    e(128, 128, 94, 74, 255)                                   # head
    e(91, 128, 24, 30, 0); e(165, 128, 24, 30, 0)              # eye patches
    e(92, 124, 9, 10, 255); e(164, 124, 9, 10, 255)            # eyes
    e(128, 152, 13, 9, 0)                                      # nose
    d.arc([104, 150, 128, 178], 20, 160, fill=0, width=8)      # smile
    d.arc([128, 150, 152, 178], 20, 160, fill=0, width=8)
    d.polygon([(128, 208), (88, 188), (88, 228)], fill=0)      # bow tie
    d.polygon([(128, 208), (168, 188), (168, 228)], fill=0)
    e(128, 208, 11, 13, 0)
    d.ellipse([122, 202, 134, 214], fill=255)
    return im.resize((64, 64), Image.LANCZOS).point(lambda v: 255 if v >= 128 else 0).convert("1")


def hat_layers():
    """The cap as (lit pixels, silhouette) 64x64 layers, same 4x drawing scale as panda()."""
    lit = Image.new("L", (256, 256), 0)
    sil = Image.new("L", (256, 256), 0)
    dl, ds = ImageDraw.Draw(lit), ImageDraw.Draw(sil)
    for d in (dl, ds):
        d.rounded_rectangle([98, 4, 158, 58], radius=6, fill=255)    # crown
        d.rounded_rectangle([78, 54, 178, 66], radius=5, fill=255)   # brim
    ds.rectangle([78, 66, 178, 70], fill=255)       # dark line under the brim, part of the cap
    dl.rectangle([98, 34, 158, 46], fill=0)         # dark band
    shrink = lambda im: im.resize((64, 64), Image.LANCZOS).point(lambda v: 255 if v >= 128 else 0).convert("1")
    return shrink(lit), shrink(sil)


def hat_sprite():
    """Crop the cap layers to their bounding box: (lit, mask, x, y)."""
    lit, sil = hat_layers()
    box = sil.getbbox()
    return lit.crop(box), sil.crop(box), box[0], box[1]


def with_hat(img, hat, mask, x, y):
    """What the firmware shows: clear the cap's silhouette, then draw its lit pixels."""
    out = img.copy()
    out.paste(0, (x, y), mask)
    out.paste(1, (x, y), hat)
    return out


def fit_font(lines):
    """Largest bold font (max 15 px) where every line fits the text column."""
    for size in range(15, 7, -1):
        f = ImageFont.truetype(BOLD, size)
        if all(f.getbbox(t)[2] <= TEXT_W for t in lines):
            return f
    return ImageFont.truetype(BOLD, 8)


def screen(p, lines):
    img = Image.new("1", (128, 64), 0)
    img.paste(p, (0, 0))
    d = ImageDraw.Draw(img)
    f = fit_font(lines)
    asc, desc = f.getmetrics()
    step = asc + desc + 2
    y = (64 - step * len(lines) + 2) // 2
    for t in lines:
        d.text((TEXT_X, y), t, font=f, fill=1)
        y += step
    return img


def preview(img, path):
    z = 6
    big = img.convert("L").resize((img.width * z, img.height * z), Image.NEAREST).convert("RGB")
    px = big.load()
    for y in range(big.height):
        for x in range(big.width):
            gap = x % z == 0 or y % z == 0
            px[x, y] = (6, 14, 28) if gap else ((140, 196, 255) if px[x, y][0] else (3, 6, 12))
    out = Image.new("RGB", (big.width + 24, big.height + 24), (20, 20, 24))
    out.paste(big, (12, 12))
    out.save(path)


def main():
    p = panda()
    hat, mask, hx, hy = hat_sprite()
    parts = ["// Power-on greeting screens, 128x64. Generated by tools/make_oled_panda.py: edit that, not this.",
             "#pragma once", ""]
    for i, (name, lines) in enumerate(SCREENS, 1):
        img = screen(p, lines)
        parts.append(f"// Screen {i}: " + " / ".join(lines) + " (panda without the cap)")
        parts.append(to_array(img, name))
        parts.append("")
        preview(with_hat(img, hat, mask, hx, hy) if i == 1 else img, PREVIEW_DIR / f"greeting_{i}_preview.png")
    parts.append("// The cap: clear GREET_HAT_MASK in black, then draw GREET_HAT in white, at its place on screen 1")
    parts.append(f"#define GREET_HAT_X {hx}")
    parts.append(f"#define GREET_HAT_Y {hy}")
    parts.append(to_array(hat, "GREET_HAT"))
    parts.append("")
    parts.append(to_array(mask, "GREET_HAT_MASK"))
    parts.append("")
    OUT_H.write_text("\n".join(parts))
    print("wrote", OUT_H.relative_to(ROOT))


if __name__ == "__main__":
    main()
