#!/usr/bin/env python3
"""Draws the panda with headphones for the Music player screen (menu -> Music player)
and writes firmware/bag_clip/music_img.h.

Two pictures, 32x32 each:
  MUSIC_PANDA_VIBE  eyes closed, enjoying it: shown while a song plays (it bobs to the beat)
  MUSIC_PANDA_WAIT  eyes open: shown while paused or when nothing plays

HOW TO EDIT: change headphones() or the eyes/mouth passed in main(), then run, from the
repository folder:
    python3 tools/make_music_panda.py
and flash firmware/bag_clip again. Check docs/images/music_panda_preview.png first
(OLED look, enlarged). The rest of the screen (disc, buttons, text) is drawn in
firmware/bag_clip/ui.cpp, uiMusic().
Needs Pillow (pip install pillow).
"""
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from PIL import Image, ImageDraw
from png_to_bitmap import to_array
from make_oled_panda import panda, oled_look

ROOT = Path(__file__).resolve().parent.parent
OUT_H = ROOT / "firmware" / "bag_clip" / "music_img.h"
PREVIEW = ROOT / "docs" / "images" / "music_panda_preview.png"
SIZE = 32


def headphones(d):
    """A band over the head and a cup on each side. The ears go (they'd only clutter
    the band at this size) and a dark gap keeps the band apart from the lit head."""
    box = [14, 8, 242, 250]
    d.arc(box, 190, 350, fill=0, width=34)            # dark gap round the band
    d.arc([b + (10 if i < 2 else -10) for i, b in enumerate(box)], 192, 348, fill=255, width=14)  # the band
    for cx in (30, 226):                              # ear cups
        d.rounded_rectangle([cx - 26, 96, cx + 26, 190], radius=20, fill=255)
        d.rounded_rectangle([cx - 15, 108, cx + 15, 178], radius=12, fill=0)


def picture(eyes):
    im = Image.new("L", (256, 256), 0)
    d = ImageDraw.Draw(im)
    panda(d, eyes=eyes)
    no_ears = Image.new("L", im.size, 0)                    # black out the ears, not the head
    m = ImageDraw.Draw(no_ears)
    m.ellipse([12, 26, 92, 106], fill=255); m.ellipse([164, 26, 244, 106], fill=255)
    m.ellipse([34, 54, 222, 202], fill=0)
    im.paste(0, mask=no_ears)
    headphones(d)
    return im.resize((SIZE, SIZE), Image.LANCZOS).point(lambda v: 255 if v >= 120 else 0).convert("1")


def main():
    vibe, wait = picture("closed"), picture("open")
    h = ["// Panda with headphones for the Music player. GENERATED by tools/make_music_panda.py:",
         "// edit the drawing there, run it, and flash again.",
         "#pragma once", "",
         "// Eyes closed, enjoying the song (shown while playing).", to_array(vibe, "MUSIC_PANDA_VIBE"), "",
         "// Eyes open (paused, or nothing playing).", to_array(wait, "MUSIC_PANDA_WAIT"), ""]
    OUT_H.write_text("\n".join(h))
    sheet = Image.new("1", (SIZE * 2 + 8, SIZE), 0)
    sheet.paste(vibe, (0, 0)); sheet.paste(wait, (SIZE + 8, 0))
    oled_look(sheet, 8).save(PREVIEW)
    print(f"wrote {OUT_H.relative_to(ROOT)} and {PREVIEW.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
